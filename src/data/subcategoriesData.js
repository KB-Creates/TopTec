export const getSubcategoryData = (path) => {
  if (!path) return null;
  const cleanPath = path.replace(/\/$/, '');

  if (subcategoriesRegistry[cleanPath]) {
    return subcategoriesRegistry[cleanPath];
  }

  const keys = Object.keys(subcategoriesRegistry);
  const matchedKey = keys.find(k => cleanPath.startsWith(k));
  if (matchedKey) {
    return subcategoriesRegistry[matchedKey];
  }

  // Fallback: derive title from last segment of path if unlisted
  const segments = cleanPath.split('/').filter(Boolean);
  const lastSegment = segments[segments.length - 1] || 'Subcategory';
  const formattedTitle = lastSegment
    .split('-')
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');

  return {
    title: formattedTitle,
    parentCategory: 'Category',
    parentCategorySlug: '',
    description: `Specialized ${formattedTitle} solutions for high-performance cleanrooms and pharmaceutical operations.`,
    keywords: [lastSegment.replace('-', ' ')],
  };
};
